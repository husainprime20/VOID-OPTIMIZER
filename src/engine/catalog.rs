//! The VOID tweak catalog.
//!
//! Every entry is a *documented, reversible* system-level change. VOID never
//! touches game files, never injects into processes, and never disables
//! anti-cheat. It only edits Windows configuration through the official
//! `reg` / `powercfg` / `bcdedit` / `netsh` / `sc` / `fsutil` interfaces.

/// A single reversible operation.
pub enum Action {
    /// `reg add <key> /v <value> /t <type> /d <data> /f`
    Reg(&'static str, &'static str, &'static str, &'static str),
    /// `reg delete <key> /v <value> /f`
    RegDel(&'static str, &'static str),
    /// Arbitrary documented command.
    Cmd(&'static str, &'static [&'static str]),
    /// Disable + stop a service.
    Svc(&'static str),
    /// Re-enable + start a service.
    SvcEnable(&'static str),
    /// Engine-handled routine (dynamic values, enumeration, launch…).
    Special(&'static str),
}

pub fn action_text(a: &Action) -> String {
    match a {
        Action::Reg(k, v, t, d) => format!("reg add \"{}\" /v \"{}\" /t {} /d {} /f", k, v, t, d),
        Action::RegDel(k, v) => format!("reg delete \"{}\" /v \"{}\" /f", k, v),
        Action::Cmd(p, args) => format!("{} {}", p, args.join(" ")),
        Action::Svc(n) => format!("sc config {} start= disabled  ·  sc stop {}", n, n),
        Action::SvcEnable(n) => format!("sc config {} start= auto  ·  sc start {}", n, n),
        Action::Special(s) => format!("void::{}", s),
    }
}

pub struct Tweak {
    pub id: &'static str,
    pub name: &'static str,
    pub cat: &'static str,
    pub desc: &'static str,
    pub why: &'static str,
    /// 0 = safe, 1 = moderate, 2 = advanced
    pub risk: u8,
    pub reboot: bool,
    /// One-shot action instead of a persistent toggle.
    pub once: bool,
    pub apply: &'static [Action],
    pub revert: &'static [Action],
}

pub struct Profile {
    pub id: &'static str,
    pub name: &'static str,
    pub tagline: &'static str,
    pub note: &'static str,
    pub tweaks: &'static [&'static str],
}

